export const PIXEL_FONT_FAMILY = "LOWPO11Y Pixel";

export function pixelFontGlyphs(): PixelGlyph[] {
  return Object.entries(GLYPHS).map(([ch, spec]) => {
    const rows = spec.split(" ");
    if (rows.length !== 7 && rows.length !== 9) throw new Error(`Glyph ${ch} has ${rows.length} rows`);
    if (rows.some((r) => r.length !== 5)) throw new Error(`Glyph ${ch} has a row that isn't 5 wide`);
    // one empty row above the caps: 8 pixels of ascent, 2 of descent
    return { codepoint: ch.codePointAt(0)!, rows: [".....", ...rows] };
  });
}

/** The font file (TrueType), byte-for-byte reproducible. */
export function buildPixelFont(): Uint8Array {
  return writePixelFont({
    family: PIXEL_FONT_FAMILY,
    version: "1.000",
    copyright: "LOWPO11Y Pixel. Drawn for LOWPO11Y and dedicated to the public domain (CC0 1.0).",
    license: "CC0 1.0 Universal. No rights reserved: use, modify and redistribute this font for any purpose without asking.",
    licenseUrl: "https://creativecommons.org/publicdomain/zero/1.0/",
    unit: 100,
    ascent: 8,
    descent: 2,
    capHeight: 7,
    xHeight: 5,
    advance: 6,
    glyphs: pixelFontGlyphs(),
  });
}
