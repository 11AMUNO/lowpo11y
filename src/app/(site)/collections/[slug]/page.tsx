import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { cache } from "react";
import { Badge } from "@/components/ui/badge";
import { buttonClasses } from "@/components/ui/button";
import { Panel } from "@/components/ui/panel";
import { Container, PageHeader, Prose } from "@/components/site/page-header";
import { AssetCard } from "@/features/catalog/asset-card";
import { getPublicCollection } from "@/lib/assets/collections";
import { assetPath } from "@/lib/assets/schemas";
import { PUBLIC, withDb } from "@/lib/db";
import { formatBytes, formatCount, formatDate, pluralise } from "@/lib/format";
import { renderMarkdown } from "@/lib/markdown";
import { absoluteUrl } from "@/lib/site";

export const dynamic = "force-dynamic";

const load = cache((slug: string) => withDb(PUBLIC, (q) => getPublicCollection(q, slug)));

export async function generateMetadata({ params }: PageProps<"/collections/[slug]">): Promise<Metadata> {
  const data = await load((await params).slug);
  if (!data) return { title: "Collection not found", robots: { index: false } };
  const c = data.collection;
  const image = data.items.find((i) => i.thumbnail_url)?.thumbnail_url;
  return {
    title: c.title,
    description: c.summary || `A LOWPO11Y pack of ${data.items.length} assets.`,
    alternates: { canonical: `/collections/${c.slug}` },
    openGraph: { title: c.title, description: c.summary, url: `/collections/${c.slug}`, images: image ? [{ url: absoluteUrl(image), alt: "" }] : undefined },
  };
}

export default async function CollectionPage({ params }: PageProps<"/collections/[slug]">) {
  const data = await load((await params).slug);
  if (!data) notFound();
  const { collection: c, items } = data;
  const description = renderMarkdown(c.description_md);

  const licences = new Map<string, { label: string; count: number }>();
  for (const i of items) {
    const key = i.licence_code ?? "unknown";
    const entry = licences.get(key) ?? { label: i.licence_short ?? "Unknown", count: 0 };
    entry.count++;
    licences.set(key, entry);
  }
  const needCredit = items.filter((i) => i.attribution_required);
  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "CollectionPage",
    name: c.title,
    description: c.summary || undefined,
    url: absoluteUrl(`/collections/${c.slug}`),
    hasPart: items.map((i) => ({ "@type": "CreativeWork", name: i.title, url: absoluteUrl(assetPath(i)) })),
  };

  return (
    <Container wide>
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd).replace(/</g, "\\u003c") }} />
      <PageHeader
        title={c.title}
        description={c.summary || undefined}
        breadcrumbs={[{ label: "Home", href: "/" }, { label: "Collections", href: "/collections" }, { label: c.title }]}
        telemetry={[pluralise(items.length, "asset"), c.bundle_size_bytes ? `ZIP ${formatBytes(Number(c.bundle_size_bytes))}` : null, c.bundle_built_at ? `built ${formatDate(c.bundle_built_at)}` : null]
          .filter(Boolean)
          .join(" // ")}
        actions={items.some((i) => i.is_demo) ? <Badge title="Generated by LOWPO11Y for demonstration">Demo</Badge> : null}
      />

      <div className="grid items-start gap-5 py-5 lg:grid-cols-[minmax(0,1fr)_23rem] xl:grid-cols-[minmax(0,1fr)_25rem]">
        <aside aria-label="Download pack" className="flex flex-col gap-4 lg:order-2">
          <Panel title="Download pack">
            {c.bundle_public_key ? (
              <a href={`/api/collections/${c.slug}/download`} rel="nofollow" className={buttonClasses("primary", "lg", "w-full")}>
                [ Download ZIP <span className="text-muted">{formatBytes(Number(c.bundle_size_bytes ?? 0))}</span> ]
              </a>
            ) : (
              <p className="text-[13px] text-muted">The pack ZIP is being rebuilt. Download the assets one at a time below in the meantime.</p>
            )}
            <p className="mt-3 text-xs leading-relaxed text-muted">
              One folder per asset with its files and LICENSE.txt, plus NOTICE.txt (every licence in one place) and manifest.json with checksums.
            </p>
            {c.bundle_sha256 ? (
              <p className="mt-2 font-ocr text-[11px] tracking-[0.04em] break-all text-muted">SHA-256 {c.bundle_sha256}</p>
            ) : null}
          </Panel>
          <Panel title="Licences in this pack">
            <ul>
              {[...licences.values()].map((l) => (
                <li key={l.label} className="flex items-baseline justify-between border-b border-dashed border-rule-strong py-1.5 text-[13px] last:border-0">
                  <span className="text-fg">{l.label}</span>
                  <span className="font-ocr text-xs text-muted">{pluralise(l.count, "asset")}</span>
                </li>
              ))}
            </ul>
            <p className="mt-3 text-xs leading-relaxed text-muted">
              {needCredit.length
                ? `${pluralise(needCredit.length, "asset")} ${needCredit.length === 1 ? "needs" : "need"} a credit line. NOTICE.txt in the ZIP has the exact text.`
                : "No credit is required for anything in this pack."}{" "}
              <Link href="/licences" className="text-bright underline underline-offset-4">
                How licences work
              </Link>
            </p>
          </Panel>
          <p className="px-1 font-ocr text-[11px] tracking-[0.06em] text-muted uppercase">Pack downloads: {formatCount(c.download_count)}</p>
        </aside>

        <div className="flex min-w-0 flex-col gap-5 lg:order-1">
          <section aria-labelledby="members-title">
            <h2 id="members-title" className="type-panel mb-3">
              // In this pack
            </h2>
            <ul className="grid grid-cols-[repeat(auto-fill,minmax(10.5rem,1fr))] gap-3">
              {items.map((item, i) => (
                <li key={item.id} className="flex">
                  <AssetCard item={item} priority={i < 6} />
                </li>
              ))}
            </ul>
          </section>
          {description ? (
            <Panel title="About this pack">
              <Prose>
                <div dangerouslySetInnerHTML={{ __html: description }} />
              </Prose>
            </Panel>
          ) : null}
        </div>
      </div>
    </Container>
  );
}
